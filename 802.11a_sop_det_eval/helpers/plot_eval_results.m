function plot_eval_results(cfg, results, out_dir)
%PLOT_EVAL_RESULTS  Generate the full figure set from a (cfg, results)
%
%   Author:  Panos Alevizos <bigpan27@gmail.com>
%   AI assistance: Claude (Anthropic) -- code drafting and verification.
%   Copyright (c) 2026 Panos Alevizos. Licensed under CC BY 4.0.
%     https://creativecommons.org/licenses/by/4.0/
%
% pair as produced by eval_80211_sop_e2e_run -> eval_80211_sop_kernel.
%
% Figures (saved to out_dir):
% 00_pd_vs_snr_random_cfo.png
% 01_pd_vs_cfo.png
% 02_pd_vs_cfo_snr<SNR1>.png
% 03_pd_vs_cfo_snr<SNR2>.png
% 04_pd_pfa_vs_residual_jnr_snr<SNR1>.png
% 05_pd_pfa_vs_residual_jnr_snr<SNR2>.png
% 06_pd_pfa_vs_jammer_offset.png
%
% Conventions match eval_sop_baseline_v1: locked color/marker per
% detector (AC blue dotted, XC_SINGLE_MF orange star, XC_BANK green
% diamond). Plots use the median-CFAR column (index 2 of the last
% results dim).

    if ~exist(out_dir, 'dir'); mkdir(out_dir); end

        %% ---- Locked detector styling -----------------------------------
        det_color_rgb = [0.000 0.447 0.741;
        0.850 0.325 0.098;
        0.466 0.674 0.188];
        det_marker_str = {'o', '*', 'd'};
        det_linestyle_str = {':', '-', '-'};
        det_linewidth = [ 2, 1.5, 1.5 ];
        det_markersize = [ 7, 9, 7 ];

        %% ---- Channel description string --------------------------------
        if cfg.channel_id == 1
            channel_descr_str = sprintf('TDL-D, DS=%.0fns, F_d=%.0fHz', ...
                cfg.tdl_delay_spread_s*1e9, cfg.tdl_f_doppler_hz);
        else
            channel_descr_str = 'AWGN';
        end

        %% ---- Sweep 0 ---------------------------------------------------
        plot_pd_vs_axis(out_dir, '00_pd_vs_snr_random_cfo.png', ...
            cfg.snr_grid_sweep0_db, ...
            results.arr_pd_sweep0(:, :, 2), ...
            results.arr_pfa_sweep0(:, 1, 2), ...
            cfg.detectors_str, ...
            det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize, ...
            'SNR (dB)', 'P_d', ...
            sprintf('Sweep 0: P_d vs SNR (random CFO ~ U[\\pm%g kHz], no jammer; %s; median CFAR)', ...
            cfg.random_cfo_max_freq/1e3, channel_descr_str));

        %% ---- Sweep 1 ---------------------------------------------------
        plot_pd_vs_cfo_panels(out_dir, '01_pd_vs_cfo.png', ...
            cfg.cfo_grid_sweep1_khz, results.arr_pd_sweep1(:, :, :, 2), ...
            results.arr_pfa_sweep1(:, :, 2), ...
            cfg.detectors_str, ...
            cfg.snr_sweep1_panels_db, cfg.jammer_on_sweep1_panel, ...
            cfg.jnr_sweep1_panel4_db, cfg.jam_offs_sweep1_panel4_mhz, ...
            channel_descr_str, ...
            det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize);

        %% ---- Sweep 2 ---------------------------------------------------
        for k_snr = 1:numel(cfg.snr_sweep2_db)
            plot_pd_vs_cfo_jammer_pos(out_dir, ...
                sprintf('%02d_pd_vs_cfo_snr%d.png', 1 + k_snr, cfg.snr_sweep2_db(k_snr)), ...
                cfg.cfo_grid_sweep2_khz, ...
                squeeze(results.arr_pd_sweep2(:, k_snr, :, :, 2)), ...
                squeeze(results.arr_pfa_sweep2(:, k_snr, :, 2)), ...
                cfg.detectors_str, cfg.jam_offs_sweep2_mhz, cfg.snr_sweep2_db(k_snr), cfg.jnr_sweep2_db, ...
                channel_descr_str, ...
                det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize);
        end

        %% ---- Sweep 3 (2x4 P_d/P_fa, per-SNR figure) --------------------
        for k_snr = 1:numel(cfg.snr_sweep3_db)
            plot_pd_pfa_vs_residual_jnr(out_dir, ...
                sprintf('%02d_pd_pfa_vs_residual_jnr_snr%d.png', 3 + k_snr, cfg.snr_sweep3_db(k_snr)), ...
                cfg.res_jnr_grid_sweep3_db, ...
                squeeze(results.arr_pd_sweep3(:, k_snr, :, :, 2)), ...
                squeeze(results.arr_pfa_sweep3(:, k_snr, :, :, 2)), ...
                cfg.detectors_str, cfg.jam_types_sweep3_str, ...
                cfg.snr_sweep3_db(k_snr), ...
                sprintf('CFO \\sim U[\\pm%g kHz], %s', cfg.random_cfo_max_freq/1e3, channel_descr_str), ...
                det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize);
        end

        %% ---- Sweep 4 (2x2 P_d/P_fa, single figure) ---------------------
        plot_pd_pfa_vs_jammer_offset(out_dir, '06_pd_pfa_vs_jammer_offset.png', ...
            cfg.jam_offs_grid_sweep4_mhz, ...
            results.arr_pd_sweep4(:, :, :, 2), ...
            results.arr_pfa_sweep4(:, :, :, 2), ...
            cfg.sweep4_det_str, cfg.snr_sweep4_db, cfg.jnr_sweep4_db, ...
            channel_descr_str, ...
            det_color_rgb(cfg.sweep4_det_idx, :), det_marker_str(cfg.sweep4_det_idx), ...
            det_linestyle_str(cfg.sweep4_det_idx), det_linewidth(cfg.sweep4_det_idx), ...
            det_markersize(cfg.sweep4_det_idx));

        fprintf('All figures saved to %s\n', out_dir);
    end

    %% ====================================================================
    %% PLOT HELPERS (extracted from eval_sop_baseline_v1; internal use)
    %% ====================================================================

    function plot_pd_vs_axis(out_dir, fname_str, x_axis, arr_pd, arr_pfa_scalar, ...
        det_str_cell, ...
        det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize, ...
        xlabel_str, ylabel_str, title_str)
        n_det = size(arr_pd, 1);
        fig = figure('Name', title_str, 'Position', [40 40 800 500]);
        hold on; grid on;
        for k = 1:n_det
            plot(x_axis, arr_pd(k, :), ...
                'LineStyle', det_linestyle_str{k}, 'Marker', det_marker_str{k}, ...
                'MarkerSize', det_markersize(k), 'LineWidth', det_linewidth(k), ...
                'Color', det_color_rgb(k, :), ...
                'DisplayName', sprintf('%s (P_fa = %.4f)', det_str_cell{k}, arr_pfa_scalar(k)));
        end
        xlabel(xlabel_str); ylabel(ylabel_str); ylim([0 1.05]);
        title(title_str, 'FontWeight', 'bold', 'FontSize', 10);
        legend('Location', 'best', 'Interpreter', 'none');
        saveas(fig, fullfile(out_dir, fname_str));
    end

    function plot_pd_vs_cfo_panels(out_dir, fname_str, ...
        cfo_grid_khz, arr_pd_3d, arr_pfa_panel, ...
        det_str_cell, ...
        snr_panels_db, jammer_on_panel, jnr_panel_db, jam_offs_panel_mhz, ...
        channel_descr_str, ...
        det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize)
        n_det = size(arr_pd_3d, 1);
        n_panels = numel(snr_panels_db);
        fig = figure('Name', 'Pd vs CFO', 'Position', [40 40 1500 900]);
        sgtitle(sprintf('Sweep 1: P_d vs CFO, 4 panels (%s)', ...
            channel_descr_str), 'FontWeight', 'bold', 'FontSize', 10);
        for k_panel = 1:n_panels
            subplot(2, 2, k_panel); hold on; grid on;
            for k = 1:n_det
                plot(cfo_grid_khz, squeeze(arr_pd_3d(k, k_panel, :)).', ...
                    'LineStyle', det_linestyle_str{k}, 'Marker', det_marker_str{k}, ...
                    'MarkerSize', det_markersize(k), 'LineWidth', det_linewidth(k), ...
                    'Color', det_color_rgb(k, :), ...
                    'DisplayName', sprintf('%s (P_fa = %.3f)', det_str_cell{k}, arr_pfa_panel(k, k_panel)));
            end
            ylim([0 1.05]); xlabel('CFO (kHz)'); ylabel('P_d');
            if jammer_on_panel(k_panel) ~= 0
                title(sprintf('SNR = %+d dB, CW jammer @ %+.2f MHz, JNR = %d dB', ...
                    snr_panels_db(k_panel), jam_offs_panel_mhz, jnr_panel_db));
            else
                title(sprintf('SNR = %+d dB, no jammer', snr_panels_db(k_panel)));
            end
            legend('Location', 'south', 'Interpreter', 'none');
        end
        saveas(fig, fullfile(out_dir, fname_str));
    end

    function plot_pd_vs_cfo_jammer_pos(out_dir, fname_str, ...
        cfo_grid_khz, arr_pd_3d, arr_pfa_pos, ...
        det_str_cell, jam_offs_mhz, snr_db, jnr_db, ...
        channel_descr_str, ...
        det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize)
        n_det = size(arr_pd_3d, 1);
        n_pos = numel(jam_offs_mhz);
        pos_labels = {'on-comb', 'off-comb'};
        fig = figure('Name', sprintf('Pd vs CFO @ SNR=%d', snr_db), ...
        'Position', [40 40 1500 520]);
        sgtitle(sprintf('Sweep 2: P_d vs CFO, on/off-comb CW (SNR = %+d dB, JNR = %d dB; %s)', ...
            snr_db, jnr_db, channel_descr_str), 'FontWeight', 'bold', 'FontSize', 10);
        for k_pos = 1:n_pos
            subplot(1, n_pos, k_pos); hold on; grid on;
            for k = 1:n_det
                plot(cfo_grid_khz, squeeze(arr_pd_3d(k, k_pos, :)).', ...
                    'LineStyle', det_linestyle_str{k}, 'Marker', det_marker_str{k}, ...
                    'MarkerSize', det_markersize(k), 'LineWidth', det_linewidth(k), ...
                    'Color', det_color_rgb(k, :), ...
                    'DisplayName', sprintf('%s (P_fa = %.3f)', det_str_cell{k}, arr_pfa_pos(k, k_pos)));
            end
            ylim([0 1.05]); xlabel('CFO (kHz)'); ylabel('P_d');
            title(sprintf('SNR = %+d dB, JNR = %d dB, jammer %s @ %+.3f MHz', ...
                snr_db, jnr_db, pos_labels{k_pos}, jam_offs_mhz(k_pos)));
            legend('Location', 'south', 'Interpreter', 'none');
        end
        saveas(fig, fullfile(out_dir, fname_str));
    end

    function plot_pd_pfa_vs_residual_jnr(out_dir, fname_str, ...
        res_jnr_grid_db, arr_pd_3d, arr_pfa_3d, ...
        det_str_cell, jam_types_cell, snr_db, ...
        cfo_descr_str, ...
        det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize) %#ok<INUSD>
        n_det = size(arr_pd_3d, 1);
        n_types = numel(jam_types_cell);
        fig = figure('Name', sprintf('Pd & Pfa vs residual JNR @ SNR=%d', snr_db), ...
        'Position', [40 40 1700 900]);
        sgtitle(sprintf(['Sweep 3: P_d (top row) and P_{fa} (bottom row) vs residual JNR ' ...
            '(SNR = %+d dB, %s, median CFAR)'], ...
            snr_db, cfo_descr_str), 'FontWeight', 'bold', 'FontSize', 10);
        for k_type = 1:n_types
            % ----- Top row: P_d -----
            subplot(2, n_types, k_type); hold on; grid on;
            for k = 1:n_det
                plot(res_jnr_grid_db, squeeze(arr_pd_3d(k, k_type, :)).', ...
                    'LineStyle', '-', 'Marker', det_marker_str{k}, ...
                    'MarkerSize', det_markersize(k), 'LineWidth', det_linewidth(k), ...
                    'Color', det_color_rgb(k, :), 'DisplayName', det_str_cell{k});
            end
            ylim([-0.02 1.05]); xlabel('Residual JNR (dB)'); ylabel('P_d');
            title(sprintf('jammer = %s', strrep(jam_types_cell{k_type}, '_', '\_')));
            if k_type == 1
                legend('Location', 'southwest', 'Interpreter', 'none', 'FontSize', 8);
            end

            % ----- Bottom row: P_fa (adaptive y-zoom per panel) -----
            subplot(2, n_types, n_types + k_type); hold on; grid on;
            max_pfa_panel = 0;
            for k = 1:n_det
                pfa_curve = squeeze(arr_pfa_3d(k, k_type, :)).';
                max_pfa_panel = max(max_pfa_panel, max(pfa_curve));
                plot(res_jnr_grid_db, pfa_curve, ...
                    'LineStyle', '--', 'Marker', det_marker_str{k}, ...
                    'MarkerSize', det_markersize(k), 'LineWidth', det_linewidth(k), ...
                    'Color', det_color_rgb(k, :), 'MarkerFaceColor', 'none', ...
                    'DisplayName', det_str_cell{k});
            end
            ylim_top = max(0.10, ceil(max_pfa_panel * 10) / 10 + 0.05);
            ylim([-0.005 ylim_top]);
            xlabel('Residual JNR (dB)'); ylabel('P_{fa}');
            title(sprintf('jammer = %s', strrep(jam_types_cell{k_type}, '_', '\_')));
        end
        saveas(fig, fullfile(out_dir, fname_str));
    end

    function plot_pd_pfa_vs_jammer_offset(out_dir, fname_str, ...
        offset_mhz, arr_pd_3d, arr_pfa_3d, ...
        det_str_cell, snr_db_v, jnr_db, ...
        channel_descr_str, ...
        det_color_rgb, det_marker_str, det_linestyle_str, det_linewidth, det_markersize) %#ok<INUSD>
        n_det = size(arr_pd_3d, 1);
        n_snr = numel(snr_db_v);
        fig = figure('Name', 'Pd & Pfa vs jammer offset', 'Position', [40 40 1500 900]);
        sgtitle(sprintf(['Sweep 4: P_d (top row) and P_{fa} (bottom row) vs 1-MHz-noise carrier offset ' ...
            '(random CFO, %s, median CFAR)'], ...
            channel_descr_str), 'FontWeight', 'bold', 'FontSize', 10);
        for k_snr = 1:n_snr
            % ----- Top row: P_d -----
            subplot(2, n_snr, k_snr); hold on; grid on;
            for k_sc = -4:4
                xline(k_sc * 1.25, ':', 'Color', [0.7 0.7 0.7], 'HandleVisibility', 'off');
            end
            min_pd = 1;
            for k = 1:n_det
                pd_curve = squeeze(arr_pd_3d(k, k_snr, :)).';
                min_pd = min(min_pd, min(pd_curve));
                plot(offset_mhz, pd_curve, 'LineStyle', '-', 'Marker', det_marker_str{k}, ...
                    'MarkerSize', det_markersize(k), 'LineWidth', det_linewidth(k), ...
                    'Color', det_color_rgb(k, :), 'DisplayName', det_str_cell{k});
            end
            xlim([min(offset_mhz) max(offset_mhz)]);
            if min_pd > 0.9
                ylim([0.9 1.005]);
            else
                ylim([-0.02 1.05]);
            end
            xlabel('1-MHz-noise carrier offset (MHz)'); ylabel('P_d');
            title(sprintf('1-MHz-noise jammer -- SNR = %+d dB, random CFO, JNR = %d dB', ...
                snr_db_v(k_snr), jnr_db));
            if k_snr == 1
                legend('Location', 'south', 'Interpreter', 'none', 'FontSize', 8);
            end

            % ----- Bottom row: P_fa (adaptive y-zoom) -----
            subplot(2, n_snr, n_snr + k_snr); hold on; grid on;
            for k_sc = -4:4
                xline(k_sc * 1.25, ':', 'Color', [0.7 0.7 0.7], 'HandleVisibility', 'off');
            end
            max_pfa = 0;
            for k = 1:n_det
                pfa_curve = squeeze(arr_pfa_3d(k, k_snr, :)).';
                max_pfa = max(max_pfa, max(pfa_curve));
                plot(offset_mhz, pfa_curve, 'LineStyle', '--', 'Marker', det_marker_str{k}, ...
                    'MarkerSize', det_markersize(k), 'LineWidth', det_linewidth(k), ...
                    'Color', det_color_rgb(k, :), 'MarkerFaceColor', 'none', ...
                    'DisplayName', det_str_cell{k});
            end
            ylim_top = max(0.10, ceil(max_pfa * 10) / 10 + 0.05);
            xlim([min(offset_mhz) max(offset_mhz)]); ylim([-0.005 ylim_top]);
            xlabel('1-MHz-noise carrier offset (MHz)'); ylabel('P_{fa}');
            title(sprintf('1-MHz-noise jammer -- SNR = %+d dB, random CFO, JNR = %d dB', ...
                snr_db_v(k_snr), jnr_db));
        end
        saveas(fig, fullfile(out_dir, fname_str));
    end

